import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { httpContract } from './http-contract.js';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const ROOT_PKG = join(ROOT, 'package.json');
const SDK_OUT = join(ROOT, 'packages/sdk/src/version.gen.ts');
const SPEC = join(ROOT, 'spec/openapi.json');

const pkg = JSON.parse(readFileSync(ROOT_PKG, 'utf8')) as {
  omnigraph?: { serverVersion?: string };
};

const serverVersion = pkg.omnigraph?.serverVersion;
if (!serverVersion) {
  throw new Error(`omnigraph.serverVersion missing from ${ROOT_PKG}`);
}

const contract = httpContract(JSON.parse(readFileSync(SPEC, 'utf8')));

const sdkBody = `// AUTO-GENERATED by scripts/gen-version.ts. Do not edit by hand.
// Sources of truth: \`omnigraph.serverVersion\` in the repo-root package.json,
// and the \`Omnigraph-Http-Api\` header value required by spec/openapi.json.

/**
 * The omnigraph-server release this build of the SDK was generated against.
 */
export const SERVER_VERSION = ${JSON.stringify(serverVersion)};
/**
 * The HTTP contract every request sends and every response must carry. It is
 * the spec's header value, not the server's major.minor: a server release can
 * keep an earlier contract. Mismatched discovery or response headers fail closed.
 */
export const HTTP_API_CONTRACT = ${JSON.stringify(contract)};
export const HTTP_API_CONTRACT_HEADER = 'Omnigraph-Http-Api';
`;

writeFileSync(SDK_OUT, sdkBody);
console.log(`wrote ${SDK_OUT} (SERVER_VERSION=${serverVersion}, HTTP_API_CONTRACT=${contract})`);
